// User Management Utility Functions

/**
 * Remove Vietnamese accents from string
 * Used for generating usernames from Vietnamese names
 */
export const removeAccents = (str: string): string => {
  return str
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .replace(/đ/g, 'd')
    .replace(/Đ/g, 'D');
};

