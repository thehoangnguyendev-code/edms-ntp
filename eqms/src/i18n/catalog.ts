  language === 'vi' ? VI_MESSAGES[key] ?? fallback : fallback;

export const translateLabel = (language: ApplicationLanguage, english: string): string =>
  language === 'vi' ? VI_LABELS[english] ?? english : english;

/**
 * The language most recently painted by the provider. `tr` is for copy written in a JSX tree that does not consume the
 * context itself; it reads this module value, and the provider re-renders its subtree when the value changes.
 */
let activeLanguage: ApplicationLanguage =
  typeof window !== 'undefined' ? (readLastLanguage() ?? 'en') : 'en';

export const setCatalogLanguage = (language: ApplicationLanguage): void => {
  activeLanguage = language;
};

/** Translate a fixed UI string by its English text. Data, codes and record values never pass through here. */
export const tr = (english: string): string => translateLabel(activeLanguage, english);
