"""DEV only: (3) New Access Profile button by permission, (4) wizard without settings.user.view, wizard shows the server's real reason (SoD)."""
import os, sys, re
sys.path.insert(0, os.path.dirname(__file__))
import dcv_lib
dcv_lib.ROLES.update({'SEC': 'dcv.secadmin', 'UPD': 'dcv.sec.upd', 'NOU': 'dcv.sec.nouser'})
from dcv_lib import *
b = Browser()
def body(pg): return pg.locator('body').inner_text()
# A: update only
pg = b.page('UPD'); pg.set_default_timeout(15000)
pg.goto(BASE + '/security/access-profiles', wait_until='domcontentloaded'); pg.wait_for_timeout(4000)
txt = body(pg); b.shot('UPD', None, 'BW', 'A1-list-update-only', 'update only: list')
check('A1', 'update-only account opens the Access Profiles list', 'Access Profile' in txt, txt[:100])
check('A2', 'update-only account does NOT see the New Access Profile button', pg.get_by_role('button', name=re.compile('New Access Profile')).count() == 0, '')
pg.goto(BASE + '/security/access-profiles/wizard', wait_until='domcontentloaded'); pg.wait_for_timeout(3500)
txt = body(pg); b.shot('UPD', None, 'BW', 'A3-wizard-direct', 'update only: wizard by URL')
check('A3', 'update-only account cannot use the wizard by typing the URL', 'Access Denied' in txt, txt[:200])
# positive control
pg = b.page('SEC'); pg.set_default_timeout(15000)
pg.goto(BASE + '/security/access-profiles', wait_until='domcontentloaded'); pg.wait_for_timeout(4000)
check('A4', 'control: security manager sees the New Access Profile button', pg.get_by_role('button', name=re.compile('New Access Profile')).count() >= 1, '')
# B: no user list permission
pg = b.page('NOU'); pg.set_default_timeout(15000)
pg.goto(BASE + '/security/access-profiles', wait_until='domcontentloaded'); pg.wait_for_timeout(4000)
check('B1', 'update+assign account sees the New Access Profile button', pg.get_by_role('button', name=re.compile('New Access Profile')).count() >= 1, '')
pg.goto(BASE + '/security/access-profiles/wizard', wait_until='domcontentloaded'); pg.wait_for_timeout(3500)
pg.get_by_placeholder('e.g. Document Reviewer').fill('DCV-TEST no user list')
for _ in range(1): pg.get_by_role('button', name='Next').click(); pg.wait_for_timeout(1500)
pg.get_by_text('Pick individual permissions').click(); pg.wait_for_timeout(2500)
sr = pg.get_by_placeholder('Search permissions by name'); sr.fill('dashboard.module.view'); pg.wait_for_timeout(900)
pg.locator('div.group', has=pg.get_by_text('dashboard.module.view', exact=True)).first.locator('label').first.click(); pg.wait_for_timeout(300)
for _ in range(3): pg.get_by_role('button', name='Next').click(); pg.wait_for_timeout(1500)
pg.get_by_role('button', name='Next').click(); pg.wait_for_timeout(2500)
txt = body(pg); b.shot('NOU', None, 'BW', 'B2-users-step', 'no user-list permission: Users step')
check('B2', 'Users step explains instead of failing', 'do not have permission to list users' in txt and 'Failed to load users' not in txt, txt[-300:])
# C: SoD refusal shows the real reason
pg = b.page('SEC')
pg.goto(BASE + '/security/access-profiles/wizard', wait_until='domcontentloaded'); pg.wait_for_timeout(3500)
pg.get_by_placeholder('e.g. Document Reviewer').fill('DCV-TEST SoD refusal')
pg.get_by_role('button', name='Next').click(); pg.wait_for_timeout(2000)
pg.get_by_text('Pick individual permissions').click(); pg.wait_for_timeout(2500)
search = pg.get_by_placeholder('Search permissions by name')
for code in ['documents.revision.approve', 'documents.revision.submit_review']:
    search.fill(code); pg.wait_for_timeout(900)
    pg.locator('div.group', has=pg.get_by_text(code, exact=True)).first.locator('label').first.click(); pg.wait_for_timeout(300)
search.fill('')
for _ in range(2): pg.get_by_role('button', name='Next').click(); pg.wait_for_timeout(1500)
pg.get_by_role('button', name='Next').click(); pg.wait_for_timeout(2500)
pg.get_by_placeholder('Search users').fill('DCV Contributor 1'); pg.wait_for_timeout(2500)
pg.locator('label:has(input[id^=wizard-user-])', has_text='DCV Contributor 1').first.click(); pg.wait_for_timeout(500)
pg.get_by_role('button', name='Next').click(); pg.wait_for_timeout(1500)
pg.get_by_role('button', name='Create Access Profile').click(); pg.wait_for_timeout(2500)
pg.get_by_placeholder('Enter your reason').fill('DEV test: SoD refusal message')
pg.get_by_placeholder('Enter your username').fill('dcv.secadmin')
pg.get_by_placeholder('Enter your password').fill(PW)
pg.get_by_role('button', name='Sign & Confirm').click(); pg.wait_for_timeout(2500)
txt = body(pg); b.shot('SEC', None, 'BW', 'C1-sod-toast', 'SoD refusal: toast text')
print(txt[:600])
check('C1', 'wizard shows the server reason, not "Unexpected error"', 'Unexpected error' not in txt and re.search('conflict|segregation|incompatible|duties|cannot', txt, re.I) is not None, '')
b.close()
