-- Application Settings > Education > Schools -- universities, colleges, academies,
-- vocational secondary schools, and trade schools. Left unseeded (admins add real entries);
-- 'type' is one of com.eqms.entity.School.SchoolType.
CREATE TABLE schools (
    id          UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    name        VARCHAR(255) NOT NULL UNIQUE,
    type        VARCHAR(40) NOT NULL,
    is_active   BOOLEAN NOT NULL DEFAULT TRUE,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);
