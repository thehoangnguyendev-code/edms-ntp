-- an e-mail needs wording: a policy that now sends e-mail and has none starts from its in-app wording (the same start as turning the e-mail on in the screen)
INSERT INTO notification_template_versions (policy_id, channel, version_number, status, subject, body, action_url_template, action_label, variables_used, change_summary)
SELECT p.id, 'EMAIL', 1, 'ACTIVE', '[EQMS] ' || coalesce(v.title, e.name), '<p>' || coalesce(v.summary, '') || '</p>', coalesce(v.action_url_template, '{{actionUrl}}'),
       'Open in EQMS', v.variables_used, 'Started from the in-app wording (default channels)'
FROM notification_policies p
JOIN notification_event_definitions e ON e.code = p.event_code
LEFT JOIN notification_template_versions v ON v.policy_id = p.id AND v.channel = 'IN_APP' AND v.status = 'ACTIVE'
WHERE p.enabled_channels LIKE '%EMAIL%'
  AND NOT EXISTS (SELECT 1 FROM notification_template_versions x WHERE x.policy_id = p.id AND x.channel = 'EMAIL');
